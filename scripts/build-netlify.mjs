import {spawnSync} from 'node:child_process';
import {mkdir,writeFile,readFile,unlink} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const role=process.argv[2];
if(!['api','hr','admin','employee'].includes(role))throw new Error('Choose api, hr, admin or employee.');
process.chdir(root);
function run(args){const result=spawnSync('npm',args,{stdio:'inherit',shell:process.platform==='win32',env:process.env});if(result.error)throw result.error;if(result.status!==0)process.exit(result.status??1);}
const generatedEntry=path.join(root,'netlify/server/index.mjs');
const marker='// Generated by scripts/build-netlify.mjs';
if(role==='api'){
  run(['run','build:backend']);
  await mkdir(path.dirname(generatedEntry),{recursive:true});
  // Same Nest/Express application, password hashes, cookies and Socket.IO server.
  // The platform owns PORT; no public Render service is used in this entrypoint.
  await writeFile(generatedEntry,marker+"\nimport '../../dist/apps/api/src/main.js';\n");
  console.log('Prepared the standalone Netlify API server. No migrations or seed ran.');
}else{
  const apiUrl=process.env.API_INTERNAL_URL;
  if(!apiUrl)throw new Error('Set API_INTERNAL_URL to the staged Netlify API URL before building a portal.');
  const origin=new URL(apiUrl);
  if(origin.protocol!=='https:'||origin.username||origin.password||origin.pathname!=='/'||origin.search||origin.hash)throw new Error('API_INTERNAL_URL must be a plain HTTPS origin without credentials, a path or query.');
  if(origin.hostname.endsWith('.onrender.com'))throw new Error('The migration portal must use the new API, not a Render origin.');
  // Reusing a checkout for API and portal builds must not publish two backends.
  try{const old=await readFile(generatedEntry,'utf8');if(old.startsWith(marker))await unlink(generatedEntry);else throw new Error('An unmanaged Netlify server entry already exists.');}catch(error){if(error.code!=='ENOENT')throw error;}
  run(['exec','--','node','scripts/prepare-face-assets.mjs']);
  run(['run','build','--workspace='+ (role==='admin'?'@peopleos/super-admin':'@peopleos/web')]);
}
